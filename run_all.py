"""Regenerate answers.md: runs answer.py (as a real subprocess, exactly the way
an evaluator would) on the seven published questions and writes the verbatim
stdout of each into answers.md.

    python run_all.py
"""
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent

QUESTIONS = [
    "I scored 78% and have a budget of ₹1.5 lakh/year — which engineering colleges can I consider?",
    "Which colleges offer an MBA, and what do they cost?",
    "List the government colleges that have hostel facilities.",
    "What’s the average placement package at North Ridge Institute of Technology?",
    "Does Ganga Valley University offer a PhD in Physics?",
    "Which colleges offer scholarships for students from low-income families?",
    "Which college is best for me? I have ₹1 lakh per semester.",
]


def main():
    blocks = ["# answers.md — verbatim system output",
              "",
              "Generated by `python run_all.py`. Each block below is the exact stdout of "
              "`python answer.py \"<question>\"` — copy-pasted by the script, not edited.",
              ""]
    for i, q in enumerate(QUESTIONS, 1):
        if i > 1:
            time.sleep(4)  # stay inside free-tier requests-per-minute limits
        print(f"[{i}/{len(QUESTIONS)}] {q}", file=sys.stderr)
        proc = subprocess.run(
            [sys.executable, str(ROOT / "answer.py"), q],
            capture_output=True, text=True, encoding="utf-8", cwd=ROOT,
        )
        out = proc.stdout.strip()
        if proc.returncode != 0 or not out:
            out = f"(answer.py exited with code {proc.returncode}; stderr: {proc.stderr.strip()})"
        blocks += [f"## Q{i}. {q}", "", "```json", out, "```", ""]

    (ROOT / "answers.md").write_text("\n".join(blocks), encoding="utf-8")
    print(f"Wrote {ROOT / 'answers.md'}", file=sys.stderr)


if __name__ == "__main__":
    main()
